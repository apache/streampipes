# Starts NATS with token authentication. The token is generated by the
# entrypoint (or passed as SP_NATS_TOKEN) and written to a root-only config
# file so that it does not show up in the process list.

set -euo pipefail

CONFIG=/run/nats-server.conf
umask 077
cat > "$CONFIG" <<CONF
listen: 0.0.0.0:4222
http_port: 8222
authorization {
  token: "$SP_NATS_TOKEN"
}
CONF

exec /usr/local/bin/nats-server -c "$CONFIG"
